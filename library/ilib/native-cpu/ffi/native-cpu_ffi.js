// ============================================================================
// POINTER REGISTRY (global storage, carried over from `pointers`)
// ============================================================================

class PtrEntry {
    constructor(addr, typeId = 0) {
        this.addr = addr;
        this.typeId = typeId;
        this.valid = true;
    }
}

// A real WASM allocation's descriptor, distinguished from a Buffer/raw-value entry by
// `instanceof` at every read/write site below.
class WasmSpan {
    constructor(offset, size) {
        this.offset = offset;
        this.size = size;
    }
    bytes() {
        const out = new Uint8Array(this.size);
        for (let i = 0; i < this.size; i++) out[i] = _ncpuMem.load8(this.offset + i);
        return out;
    }
    writeBytes(data, atOffset = 0) {
        for (let i = 0; i < data.length; i++) _ncpuMem.store8(this.offset + atOffset + i, data[i]);
    }
}

const ptrRegistry = new Map();
let nextPtrId = 1000;
const NULL_PTR = -1;

// ============================================================================
// POINTER CREATION / ACCESS (carried over from `pointers`, called bare)
// ============================================================================

function ptr_new(value, valueSize, typeId = 0) {
    if (value === null || value === undefined) return NULL_PTR;
    const ptrId = nextPtrId++;
    ptrRegistry.set(ptrId, new PtrEntry(value, typeId));
    return ptrId;
}

function ptr_deref(ptrId) {
    const entry = ptrRegistry.get(ptrId);
    if (!entry || !entry.valid) return null;
    if (entry.addr instanceof WasmSpan) {
        const bytes = entry.addr.bytes();
        const end = bytes.indexOf(0);
        return Buffer.from(bytes.subarray(0, end === -1 ? bytes.length : end)).toString('utf8');
    }
    if (Buffer.isBuffer(entry.addr)) {
        const end = entry.addr.indexOf(0);
        return entry.addr.toString('utf8', 0, end === -1 ? entry.addr.length : end);
    }
    return entry.addr;
}

function ptr_null() { return NULL_PTR; }
function ptr_is_null(ptrId) { return ptrId === NULL_PTR ? 1 : 0; }

function ptr_eq(ptrId1, ptrId2) {
    if (ptrId1 === ptrId2) return 1;
    if (ptrId1 === NULL_PTR || ptrId2 === NULL_PTR) return 0;
    const e1 = ptrRegistry.get(ptrId1), e2 = ptrRegistry.get(ptrId2);
    if (!e1 || !e2 || !e1.valid || !e2.valid) return 0;
    if (e1.addr instanceof WasmSpan && e2.addr instanceof WasmSpan)
        return (e1.addr.offset === e2.addr.offset && e1.addr.size === e2.addr.size) ? 1 : 0;
    if (Buffer.isBuffer(e1.addr) && Buffer.isBuffer(e2.addr)) return e1.addr.equals(e2.addr) ? 1 : 0;
    return e1.addr === e2.addr ? 1 : 0;
}

function ptr_copy(ptrId) {
    const entry = ptrRegistry.get(ptrId);
    if (!entry || !entry.valid) return NULL_PTR;
    let dup;
    if (entry.addr instanceof WasmSpan) {
        const newOffset = _ncpuMem.alloc(entry.addr.size);
        dup = new WasmSpan(newOffset, entry.addr.size);
        dup.writeBytes(entry.addr.bytes());
    } else {
        dup = Buffer.isBuffer(entry.addr) ? Buffer.from(entry.addr) : entry.addr;
    }
    const newId = nextPtrId++;
    ptrRegistry.set(newId, new PtrEntry(dup, entry.typeId));
    return newId;
}

function ptr_update(ptrId, value, offset = 0) {
    const entry = ptrRegistry.get(ptrId);
    if (!entry || !entry.valid) return -1;
    try {
        if (entry.addr instanceof WasmSpan) {
            const data = Buffer.isBuffer(value) ? value : Buffer.from(String(value));
            const need = offset + data.length;
            if (need > entry.addr.size) {
                // Bump-allocate a fresh, bigger span and copy the old contents forward —
                // matches the Buffer branch's "grow in place" contract from the caller's
                // side (same ptrId keeps working), even though the underlying WASM bytes
                // physically moved (this allocator has no realloc-in-place primitive).
                const grownOffset = _ncpuMem.alloc(need);
                const grown = new WasmSpan(grownOffset, need);
                grown.writeBytes(entry.addr.bytes());
                entry.addr = grown;
            }
            entry.addr.writeBytes(data, offset);
        } else if (Buffer.isBuffer(entry.addr)) {
            const data = Buffer.isBuffer(value) ? value : Buffer.from(String(value));
            const need = offset + data.length;
            if (need > entry.addr.length) {
                const grown = Buffer.alloc(need);
                entry.addr.copy(grown);
                entry.addr = grown;
            }
            data.copy(entry.addr, offset);
        } else {
            entry.addr = value;
        }
        return 0;
    } catch (e) {
        return -1;
    }
}

function ptr_free(ptrId) {
    const entry = ptrRegistry.get(ptrId);
    if (!entry) return -1;
    entry.valid = false;
    ptrRegistry.delete(ptrId);
    return 0;
}

// ============================================================================
// ALLOCATION — dha = dynamic heap allocation, z = zeroed, bm = bare-metal
// ============================================================================
// Real WASM linear memory now (via _ncpuMem, a bump allocator — see the module doc
// comment at the top of this file), not a JS Buffer standing in for one. bm* still
// isn't literal OS mmap (that needs a native addon Node doesn't have built in) but WASM
// linear memory is genuine byte-addressable machine memory, a real step up from before.

function dha(size, typeId = 0) {
    if (size <= 0) return NULL_PTR;
    const offset = _ncpuMem.alloc(size);
    const ptrId = nextPtrId++;
    ptrRegistry.set(ptrId, new PtrEntry(new WasmSpan(offset, size), typeId));
    return ptrId;
}

// Fresh memory from a monotonic bump allocator is ALWAYS already zero (WASM
// zero-initializes on memory.grow, and this allocator never reuses bytes across
// allocations) — no separate zeroing pass needed, unlike Buffer.allocUnsafe vs
// Buffer.alloc, which is why dha/zdha were two different calls before.
function zdha(size, typeId = 0) { return dha(size, typeId); }

function ncpu_realloc(ptrId, size) {
    if (size <= 0) return NULL_PTR;
    const entry = ptrRegistry.get(ptrId);
    if (!entry || !entry.valid || !(entry.addr instanceof WasmSpan)) return NULL_PTR;
    const newOffset = _ncpuMem.alloc(size);
    const grown = new WasmSpan(newOffset, size);
    grown.writeBytes(entry.addr.bytes().subarray(0, Math.min(size, entry.addr.size)));
    entry.addr = grown;
    return ptrId;
}

function bmdha(size, typeId = 0) { return zdha(size, typeId); }
function bmzdha(size, typeId = 0) { return zdha(size, typeId); }
function bmrealloc(ptrId, size) { return ncpu_realloc(ptrId, size); }

// ============================================================================
// ARENA ALLOCATOR — bump allocator, bulk free
// ============================================================================
// Each arena reserves ONE fixed block from _ncpuMem's global pool up front (arena_create)
// and bump-allocates WITHIN that block itself (tracked here in JS, exactly like the old
// Buffer-subarray version) — arena_abort/destroy only ever reset THIS LOCAL offset, never
// _ncpuMem's own global bump pointer, so one arena's reset can never corrupt another
// arena's or a plain dha()'s unrelated memory in the same shared pool.

const arenaRegistry = new Map();
let nextArenaId = 1;

function arena_create(size) {
    if (size <= 0) return NULL_PTR;
    const baseOffset = _ncpuMem.alloc(size);
    const arenaId = nextArenaId++;
    arenaRegistry.set(arenaId, { baseOffset, capacity: size, offset: 0 });
    return arenaId;
}

function arena_alloc(arenaId, size) {
    if (size <= 0) return NULL_PTR;
    const arena = arenaRegistry.get(arenaId);
    if (!arena || arena.offset + size > arena.capacity) return NULL_PTR;
    const span = new WasmSpan(arena.baseOffset + arena.offset, size);
    arena.offset += size;
    const ptrId = nextPtrId++;
    ptrRegistry.set(ptrId, new PtrEntry(span, 0));
    return ptrId;
}

// Bump allocators don't free individual items — reclaim via arena_abort/destroy.
function arena_dealloc(arenaId, ptrId) { return 0; }

function arena_destroy(arenaId) {
    return arenaRegistry.delete(arenaId) ? 0 : -1;
}

function arena_abort(arenaId) {
    const arena = arenaRegistry.get(arenaId);
    if (!arena) return -1;
    arena.offset = 0;
    return 0;
}

// ============================================================================
// CONTROL
// ============================================================================

// Hard bare-metal abort — process.abort() raises SIGABRT immediately (with a
// core dump if enabled), not a clean process.exit().
function ncpu_abort() { process.abort(); }

// ============================================================================
// MESSAGING (between quickthreads) — spelling "recieve" is intentional
// ============================================================================

const _messages = new Set();

function broadcast(msg) { _messages.add(msg); }
function recieve(msg) {
    if (_messages.has(msg)) { _messages.delete(msg); return 1; }
    return 0;
}

// ── AC-facing dotted namespace: `ncpu.dha(...)`, `ncpu.abort()`, etc. ──
const ncpu = {
    dha, zdha, realloc: ncpu_realloc, bmdha, bmzdha, bmrealloc,
    arena_create, arena_alloc, arena_dealloc, arena_destroy, arena_abort,
    abort: ncpu_abort, broadcast, recieve,
};

