// AC ilib: native-cpu (ncpu) — JavaScript (Node) FFI
// Bare-metal / low-level toolkit: pointer registry (carried over from `pointers`),
// heap + bare-metal allocation, arena allocator, hard abort, quickthread messaging.
//
// Allocation (dha/zdha/bmdha/bmzdha/realloc/arena_*) is backed by REAL WASM linear
// memory (see ../../ac-compiler/wasm/ncpu_mem.wat) — genuine byte-addressable memory
// with a real bump allocator, not a JS Buffer standing in for one. `ptrRegistry` still
// unifies every pointer under one ID space exactly as before (so a pointer from `dha()`
// still works with `ptr_deref`/`ptr_update`/`ptr_free` etc.) — what changed is what an
// allocator entry's `addr` field IS: a `{wasm: true, offset, size}` descriptor instead
// of a Buffer, with a WASM branch added to every function that reads/writes `addr`.
// `ptr_new` (boxing an arbitrary already-in-hand JS value under an opaque handle) is
// unchanged — that's a reference registry, not memory allocation, and has no natural
// WASM equivalent without serializing arbitrary JS values into bytes for no real gain.

